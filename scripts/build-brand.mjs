#!/usr/bin/env node
/**
 * Brand pipeline — turns brands/<id>/brand.json into a fully-themed build.
 *
 *   BRAND=lks-attire npm run build          (default brand)
 *   BRAND=_template PALETTE=indigo-kantha npm run build
 *
 * Outputs
 *   dist/                       static assets served by the Worker (storefront + /admin)
 *   dist/brand.css              storefront design tokens (CSS custom properties)
 *   dist/admin/brand.css        admin design tokens
 *   dist/brand.json             public brand info consumed by both front-ends
 *   dist/manifest.webmanifest   PWA manifest
 *   dist/robots.txt
 *   dist/assets/ph/*.svg        generated placeholder product art in brand colours
 *   dist-seed/seed.sql          idempotent seed data (categories, zones, settings, demo catalogue)
 *   worker/src/brand.generated.ts  typed brand constants for the Worker (SEO, order prefix)
 */
