function walk(dir) {
  const out = [];
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) out.push(...walk(p));
    else out.push(p);
  }
  return out;
}

function validateBrand(b) {
  const required = ["id", "name", "tagline", "description", "orderPrefix", "domain", "locale", "palettes", "activePalette", "design", "admin", "contact", "location", "social", "seed"];
  const missing = required.filter((k) => !(k in b));
  if (missing.length) {
    console.error(`✖ brand.json missing keys: ${missing.join(", ")}`);
    process.exit(1);
  }
  if (!/^[A-Z]{2,5}$/.test(b.orderPrefix)) {
    console.error("✖ orderPrefix must be 2–5 capital letters");
    process.exit(1);
  }
  const tokens = ["bg", "surface", "surfaceAlt", "ink", "inkSoft", "primary", "primaryInk", "accent", "accentSoft", "gold", "line", "success", "danger", "motifA", "motifB", "motifC"];
  for (const [id, p] of Object.entries(b.palettes)) {
    const miss = tokens.filter((t) => !p[t]);
    if (miss.length) {
      console.error(`✖ palette "${id}" missing tokens: ${miss.join(", ")}`);
      process.exit(1);
    }
  }
}

